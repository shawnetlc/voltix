import 'package:flutter/foundation.dart';

/// Metadata definition for a Step 3 Viewing Preference option.
@immutable
class TastePreferenceDefinition {
  final String id;
  final String displayName;
  final String categoryId;
  final String categoryName;
  final String description;
  final String selectionType; // 'single', 'multi', 'boolean'
  final List<String> relatedMetadataFields;
  final List<String> relatedGenres;
  final List<String> relatedMoods;
  final List<String> opposingPreferences;
  final dynamic defaultValue;
  final String? localizationKey;

  const TastePreferenceDefinition({
    required this.id,
    required this.displayName,
    required this.categoryId,
    required this.categoryName,
    this.description = '',
    this.selectionType = 'multi',
    this.relatedMetadataFields = const [],
    this.relatedGenres = const [],
    this.relatedMoods = const [],
    this.opposingPreferences = const [],
    this.defaultValue = false,
    this.localizationKey,
  });
}

/// Metadata definition for a Step 4 Mood / Vibe option.
@immutable
class TasteMoodDefinition {
  final String id;
  final String displayName;
  final String categoryId;
  final String categoryName;
  final String description;
  final List<String> synonyms;
  final List<String> relatedJellyfinGenres;
  final List<String> relatedJellyfinTags;
  final List<String> relatedOverviewKeywords;
  final String compatiblePacing; // 'fast', 'slow-burn', 'any'
  final String compatibleTone; // 'light', 'dark', 'neutral'
  final List<String> opposingMoods;
  final double defaultScore;
  final String? localizationKey;

  const TasteMoodDefinition({
    required this.id,
    required this.displayName,
    required this.categoryId,
    required this.categoryName,
    this.description = '',
    this.synonyms = const [],
    this.relatedJellyfinGenres = const [],
    this.relatedJellyfinTags = const [],
    this.relatedOverviewKeywords = const [],
    this.compatiblePacing = 'any',
    this.compatibleTone = 'neutral',
    this.opposingMoods = const [],
    this.defaultScore = 0.0,
    this.localizationKey,
  });
}

